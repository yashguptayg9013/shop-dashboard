#!/usr/bin/env python3
"""Export the dashboard views.

  docs/data.js       every view the web dashboard draws, plus the SQL behind it
  looker-studio/     one CSV per view, to upload as Looker Studio data sources

Reads DATABASE_URL and runs psql, so nothing beyond Python 3 and psql is needed.
"""

import csv
import io
import json
import os
import subprocess
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
DB = os.environ.get("DATABASE_URL", "postgresql://localhost/shop")

# name in data.js -> query. Each is a view from sql/views/, ordered for display.
DATASETS = {
    "monthly_sales": "select * from shop.v_monthly_sales order by month",
    "category_monthly": "select * from shop.v_category_monthly order by month, category",
    "products": "select * from shop.v_product_performance order by revenue_rank",
    "stock": "select * from shop.v_stock_on_hand order by stock_value desc",
    "dead_stock": "select * from shop.v_dead_stock order by status, stock_value desc",
    "reorder": "select * from shop.v_reorder_alerts where status <> '4 OK' order by status, days_of_cover",
    "stockouts": "select * from shop.v_stockouts order by missed_revenue desc",
    "festival_prep": "select * from shop.v_festival_prep where festival_qty > 0 order by order_by, festival_value desc",
    "gst_monthly": "select * from shop.v_gst_monthly order by month",
    "gst_hsn": "select * from shop.v_gst_hsn_monthly order by month, hsn, gst_rate",
    "checks": "select * from shop.v_data_checks",
}

# Looker Studio gets the same views, plus every sales line for its own charts and filters.
LOOKER = {
    "sales_lines": "select * from shop.v_sales_lines order by invoice_ts, sale_id",
    "monthly_sales": DATASETS["monthly_sales"],
    "category_monthly": DATASETS["category_monthly"],
    "product_performance": DATASETS["products"],
    "stock_on_hand": DATASETS["stock"],
    "dead_stock": DATASETS["dead_stock"],
    "reorder_alerts": "select * from shop.v_reorder_alerts order by status, days_of_cover",
    "festival_prep": "select * from shop.v_festival_prep order by order_by, festival_value desc",
    "gst_monthly": DATASETS["gst_monthly"],
    "gst_hsn_monthly": DATASETS["gst_hsn"],
}

SQL_FILES = ["sql/01_schema.sql"] + sorted(
    "sql/views/" + f for f in os.listdir(os.path.join(ROOT, "sql/views")) if f.endswith(".sql")
)


def psql(query):
    out = subprocess.run(["psql", DB, "-X", "-q", "-At", "-v", "ON_ERROR_STOP=1", "-c", query],
                         capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit(out.stderr)
    return out.stdout


def as_json(query):
    return json.loads(psql(f"select coalesce(json_agg(t), '[]'::json) from ({query}) t"))


def main():
    data = {
        "as_of": as_json("select shop.as_of() as d")[0]["d"],
        "business": as_json("select name, gstin, state_code from shop.business")[0],
        "data_start": as_json("select min(as_of) as d from shop.opening_stock")[0]["d"],
    }
    for name, query in DATASETS.items():
        data[name] = as_json(query)
    data["sql"] = {}
    for path in SQL_FILES:
        with open(os.path.join(ROOT, path)) as f:
            data["sql"][path] = f.read()

    with open(os.path.join(ROOT, "docs/data.js"), "w") as f:
        f.write("// Generated by scripts/export.py from the PostgreSQL views. Don't edit by hand.\n")
        f.write("window.DASH = ")
        json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")

    out_dir = os.path.join(ROOT, "looker-studio")
    os.makedirs(out_dir, exist_ok=True)
    for name, query in LOOKER.items():
        text = psql(f"copy ({query}) to stdout with (format csv, header)")
        rows = list(csv.reader(io.StringIO(text)))
        with open(os.path.join(out_dir, name + ".csv"), "w", newline="") as f:
            f.write(text)
        print(f"  looker-studio/{name}.csv  {len(rows) - 1} rows")
    print(f"docs/data.js  {os.path.getsize(os.path.join(ROOT, 'docs/data.js')) // 1024} KB, data to {data['as_of']}")


if __name__ == "__main__":
    main()
